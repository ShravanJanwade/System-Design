// Generates advance-width tables for the fonts used inside diagrams, so the
// diagram layout (and the build-time layout lint) can measure labels without a DOM.
// Run with: npm run metrics
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import opentype from 'opentype.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = {
  regular: 'node_modules/@fontsource/atkinson-hyperlegible-next/files/atkinson-hyperlegible-next-latin-400-normal.woff',
  semibold: 'node_modules/@fontsource/atkinson-hyperlegible-next/files/atkinson-hyperlegible-next-latin-600-normal.woff',
  bold: 'node_modules/@fontsource/atkinson-hyperlegible-next/files/atkinson-hyperlegible-next-latin-700-normal.woff',
};

const extra = '–—×→←↑↓≈’‘“”…·µ²³½≤≥%';
const chars = [];
for (let c = 32; c <= 126; c++) chars.push(String.fromCharCode(c));
for (const ch of extra) chars.push(ch);

const out = {};
const features = {};
for (const [name, rel] of Object.entries(files)) {
  const buf = readFileSync(path.join(root, rel));
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const upm = font.unitsPerEm;
  const table = {};
  for (const ch of chars) {
    const glyph = font.charToGlyph(ch);
    table[ch] = Math.round((glyph.advanceWidth / upm) * 10000) / 10000;
  }
  out[name] = table;
  const gsub = font.tables.gsub;
  features[name] = gsub ? [...new Set(gsub.features.map((f) => f.tag))] : [];
}

const body = `// Generated by scripts/generate-font-metrics.mjs. Do not edit by hand.
// Advance widths in em units for Atkinson Hyperlegible Next.
export const fontMetrics = ${JSON.stringify(out, null, 2)} as const;
`;
writeFileSync(path.join(root, 'src/diagram/font-metrics.ts'), body);
console.log('GSUB features:', JSON.stringify(features));
console.log('Average lowercase width (semibold):', (
  'abcdefghijklmnopqrstuvwxyz'.split('').reduce((s, c) => s + out.semibold[c], 0) / 26
).toFixed(3));
