import type { Lesson, PracticeItem, Problem } from '../types';
import { lessonSegments } from './check';
import { termIds } from '../../lib/md';
import { allLessonOutlines } from '../modules';

export type LessonMeta = { idea: string; flashcards: number };

/** Which lessons link each glossary term, in curriculum order whatever order the lessons arrive in. */
export function computeTermUsage(lessons: Lesson[]): Record<string, string[]> {
  const order = new Map(allLessonOutlines.map((l, i) => [l.id, i]));
  const rank = (id: string) => order.get(id) ?? Number.MAX_SAFE_INTEGER;
  const usage: Record<string, string[]> = {};
  for (const l of lessons) {
    const ids = new Set(lessonSegments(l).flatMap((s) => termIds(s.md)));
    for (const id of ids) (usage[id] ??= []).push(l.id);
  }
  const sorted: Record<string, string[]> = {};
  for (const key of Object.keys(usage).sort()) sorted[key] = [...usage[key]!].sort((a, b) => rank(a) - rank(b));
  return sorted;
}

export function computeLessonMeta(lessons: Lesson[]): Record<string, LessonMeta> {
  const meta: Record<string, LessonMeta> = {};
  for (const l of [...lessons].sort((a, b) => a.id.localeCompare(b.id))) meta[l.id] = { idea: l.idea, flashcards: l.flashcards.length };
  return meta;
}

/** Estimation and spot-the-bottleneck questions from the lessons' quizzes, in curriculum order. */
export function computePracticePool(lessons: Lesson[]): PracticeItem[] {
  const order = new Map(allLessonOutlines.map((l, i) => [l.id, i]));
  return [...lessons]
    .sort((a, b) => (order.get(a.id) ?? 999) - (order.get(b.id) ?? 999))
    .flatMap((l) =>
      l.quiz
        .map((question, i) => ({ id: `${l.id}-q${i + 1}`, title: l.title, lessonId: l.id, question }))
        .filter((item) => item.question.kind === 'numeric' || item.question.kind === 'bottleneck'),
    );
}

export function renderPracticePool(lessons: Lesson[]): string {
  return `// Generated by scripts/generate-manifest.ts (npm run manifest). Do not edit by hand.
import type { PracticeItem } from '../types';

/** Estimation and spot-the-bottleneck questions from the lessons' quizzes, for the practice modes. */
export const practicePool: PracticeItem[] = ${JSON.stringify(computePracticePool(lessons), null, 2)};
`;
}

/** The lessons each written problem draws on, so the Problems page can filter by concept without loading problems. */
export function computeProblemConcepts(problems: Problem[]): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const p of [...problems].sort((a, b) => a.id.localeCompare(b.id))) out[p.id] = [...p.concepts];
  return out;
}

export function renderProblemConcepts(problems: Problem[]): string {
  return `// Generated by scripts/generate-manifest.ts (npm run manifest). Do not edit by hand.

/** For each written problem, the lesson ids it draws on (its concepts field). */
export const problemConcepts: Record<string, string[]> = ${JSON.stringify(computeProblemConcepts(problems), null, 2)};
`;
}

export function renderManifest(lessons: Lesson[]): string {
  return `// Generated by scripts/generate-manifest.ts (npm run manifest). Do not edit by hand.
import type { LessonMeta } from '../check/manifest';

/** For each glossary term, the lessons that link it. */
export const termUsage: Record<string, string[]> = ${JSON.stringify(computeTermUsage(lessons), null, 2)};

/** Small facts about each written lesson, available without loading the lesson. */
export const lessonMeta: Record<string, LessonMeta> = ${JSON.stringify(computeLessonMeta(lessons), null, 2)};
`;
}
